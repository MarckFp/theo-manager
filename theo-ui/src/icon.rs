/// Icon sizes, in pixels.
#[allow(missing_docs)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum IconSize {
    Xs,
    Sm,
    #[default]
    Md,
    Lg,
    Xl,
}

impl IconSize {
    fn px(self) -> u32 {
        match self {
            IconSize::Xs => 14,
            IconSize::Sm => 16,
            IconSize::Md => 20,
            IconSize::Lg => 24,
            IconSize::Xl => 32,
        }
    }
}

